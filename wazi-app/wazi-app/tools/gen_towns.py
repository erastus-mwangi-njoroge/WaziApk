#!/usr/bin/env python3
"""Generate the town lists used by the Angular and Flutter apps from data/kenya_towns.json.

    python3 tools/gen_towns.py

Edit data/kenya_towns.json (add a town to its county, or an area to a town), re-run
this script, and commit the regenerated files. CI does not regenerate them.

Stored listing values stay plain strings, exactly as before:
    "Kitengela"            a town
    "Nairobi — Kilimani"   a town + area (separated by an em dash with spaces)
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "kenya_towns.json"
TS_OUT = ROOT / "frontend" / "src" / "app" / "core" / "kenya-towns.ts"
DART_OUT = ROOT / "mobile" / "lib" / "data" / "kenya_towns.dart"

SEP = " — "

def load():
    data = json.loads(SRC.read_text(encoding="utf-8"))["counties"]
    groups, seen = [], set()
    for c in data:
        opts = []
        for t in c["towns"]:
            opts.append(t["name"])
            opts += [f'{t["name"]}{SEP}{a}' for a in t["areas"]]
        for o in opts:
            if o in seen:
                sys.exit(f"Duplicate option across counties: {o!r}")
            seen.add(o)
        groups.append((c["county"], opts))
    return groups

def q(s):
    return json.dumps(s, ensure_ascii=False)

def main():
    groups = load()
    banner = "GENERATED by tools/gen_towns.py from data/kenya_towns.json — do not edit by hand."

    ts = [f"// {banner}", "",
          "export interface TownGroup { county: string; options: string[]; }", "",
          "export const TOWN_GROUPS: TownGroup[] = ["]
    for county, opts in groups:
        ts.append(f"  {{ county: {q(county)}, options: [")
        for i in range(0, len(opts), 4):
            ts.append("    " + ", ".join(q(o) for o in opts[i:i + 4]) + ",")
        ts.append("  ] },")
    ts.append("];\n")
    TS_OUT.write_text("\n".join(ts), encoding="utf-8")

    dart = [f"// {banner}", "",
            "class TownGroup {",
            "  final String county;",
            "  final List<String> options;",
            "  const TownGroup(this.county, this.options);",
            "}", "",
            "const List<TownGroup> kTownGroups = ["]
    for county, opts in groups:
        dart.append(f"  TownGroup({q(county)}, [")
        for i in range(0, len(opts), 4):
            dart.append("    " + ", ".join(q(o) for o in opts[i:i + 4]) + ",")
        dart.append("  ]),")
    dart.append("];\n")
    DART_OUT.parent.mkdir(parents=True, exist_ok=True)
    DART_OUT.write_text("\n".join(dart), encoding="utf-8")

    total = sum(len(o) for _, o in groups)
    print(f"{len(groups)} counties, {total} options -> {TS_OUT.relative_to(ROOT)}, {DART_OUT.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
